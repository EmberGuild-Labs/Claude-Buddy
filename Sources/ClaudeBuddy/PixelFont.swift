/// A chunky 5×7 all-caps arcade font, drawn pixel by pixel like everything else.
/// Lowercase is shown as caps, accents are dropped, and anything unknown becomes "?".
enum PixelFont {
    static let glyphWidth = 5
    static let glyphHeight = 7
    /// Horizontal distance between the starts of two characters.
    static let advance = 6

    static func width(of text: String) -> Int {
        let n = normalize(text).count
        return n == 0 ? 0 : n * advance - 1
    }

    /// Draws `text` with its top row at `top` (canvas y grows upward). Returns the width drawn.
    @discardableResult
    static func draw(_ text: String, on c: inout PixelCanvas, x: Int, top: Int, color: RGBA) -> Int {
        var cx = x
        for ch in normalize(text) {
            if let rows = glyphs[ch] {
                for (r, row) in rows.enumerated() {
                    for (col, bit) in row.enumerated() where bit == "#" {
                        c.set(cx + col, top - r, color)
                    }
                }
            }
            cx += advance
        }
        return max(0, cx - x - 1)
    }

    /// Uppercases, folds accents, and maps unsupported characters to "?".
    static func normalize(_ text: String) -> [Character] {
        let folded = text.folding(options: [.diacriticInsensitive, .widthInsensitive], locale: .current).uppercased()
        var out: [Character] = []
        for ch in folded {
            switch ch {
            case "…": out += [".", "."]
            case "—", "–": out.append("-")
            case "‘", "’": out.append("'")
            case "“", "”": out.append("\"")
            case "\n", "\t": out.append(" ")
            default: out.append(glyphs[ch] == nil ? "?" : ch)
            }
        }
        return out
    }

    /// Cuts `text` to fit `maxWidth` pixels, ending in ".." when shortened.
    static func fit(_ text: String, maxWidth: Int) -> String {
        let chars = normalize(text)
        let fits = max(0, (maxWidth + 1) / advance)
        guard chars.count > fits else { return String(chars) }
        guard fits > 2 else { return String(chars.prefix(fits)) }
        let trimmed = String(chars.prefix(fits - 2)).trimmingCharacters(in: .whitespaces)
        return trimmed + ".."
    }

    /// Word-wraps into lines no wider than `maxWidth` pixels (at most `maxLines`).
    static func wrap(_ text: String, maxWidth: Int, maxLines: Int) -> [String] {
        let perLine = max(1, (maxWidth + 1) / advance)
        var lines: [String] = []
        var line = ""
        for word in String(normalize(text)).split(separator: " ") {
            let candidate = line.isEmpty ? String(word) : line + " " + word
            if candidate.count <= perLine {
                line = candidate
            } else {
                if !line.isEmpty { lines.append(line) }
                line = String(word.prefix(perLine))
            }
        }
        if !line.isEmpty { lines.append(line) }
        if lines.count > maxLines {
            lines = Array(lines.prefix(maxLines))
            lines[maxLines - 1] = fit(lines[maxLines - 1] + "..", maxWidth: maxWidth)
        }
        return lines
    }

