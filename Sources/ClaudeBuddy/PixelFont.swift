/// 7×7 pixel icons for the billboard.
enum PixelIcon {
    case todo, done, missing, quiz, discussion, event, star, close

    static let size = 7

    func draw(on c: inout PixelCanvas, x: Int, top: Int, tint: RGBA, carve: RGBA) {
        for (r, row) in rows.enumerated() {
            for (col, ch) in row.enumerated() {
                switch ch {
                case "#": c.set(x + col, top - r, tint)
                case "o": c.set(x + col, top - r, carve)
                default: break
                }
            }
        }
    }

    private var rows: [String] {
        switch self {
        case .todo: ["..###..", ".#...#.", "#.....#", "#.....#", "#.....#", ".#...#.", "..###.."]
        case .done: [".......", "......#", ".....##", "#...##.", "##.##..", ".###...", "..#...."]
        case .missing: ["..###..", ".##o##.", "###o###", "###o###", "#######", ".##o##.", "..###.."]
        case .quiz: ["..###..", ".#...#.", ".....#.", "....#..", "...#...", ".......", "...#..."]
        case .discussion: ["#######", "#.....#", "#.#.#.#", "#.....#", "#######", ".##....", ".#....."]
        case .event: [".#...#.", "#######", "#.....#", "#.#.#.#", "#.....#", "#.#.#.#", "#######"]
        case .star: ["...#...", "...#...", "#######", ".#####.", "..###..", ".##.##.", ".#...#."]
        case .close: ["#.....#", ".#...#.", "..#.#..", "...#...", "..#.#..", ".#...#.", "#.....#"]
        }
    }
}
